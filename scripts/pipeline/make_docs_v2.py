def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for fn in (build_ai_v2, build_originality):
        p = fn()
        print("  %-38s %7.0f KB" % (p.name, p.stat().st_size / 1024))
    old = OUT / "人工智能工具使用说明.docx"
    if old.exists():
        old.unlink()
        print("  已删除旧命名的《人工智能工具使用说明.docx》（官方叫…情况说明）")


if __name__ == "__main__":
    main()
